#[test]
fn a_directory_list_stops_at_the_request_size_and_is_left_whole() {
    // Two records of 32 bytes fit 64 exactly; a third does not fit, and the list is unchanged.
    let mut buf = DirentBuf::new(64);
    assert!(buf.as_bytes().is_empty());
    buf.push(1, 1, EntryKind::File, b"a").unwrap();
    buf.push(2, 2, EntryKind::Symlink, b"12345678").unwrap();
    assert_eq!(buf.as_bytes().len(), 64);
    let before = buf.clone();
    assert_eq!(
        buf.push(3, 3, EntryKind::File, b"c"),
        Err(DirPushError::Full)
    );
    assert_eq!(buf, before);
    // A record of 33 bytes is padded to 40, and does not fit 39.
    let mut small = DirentBuf::new(39);
    assert_eq!(
        small.push(1, 1, EntryKind::File, b"123456789"),
        Err(DirPushError::Full)
    );
    let mut fits = DirentBuf::new(40);
    fits.push(1, 1, EntryKind::File, b"123456789").unwrap();
    let rec = fits.as_bytes();
    assert_eq!(rec.len(), 40);
    let (head, rest) = Dirent::read_prefix(rec).unwrap();
    assert_eq!(
        head,
        Dirent {
            ino: 1,
            off: 1,
            namelen: 9,
            typ: 8
        }
    );
    assert_eq!(rest, b"123456789\0\0\0\0\0\0\0");
    // A size below one record holds nothing.
    assert_eq!(
        DirentBuf::new(0).push(1, 1, EntryKind::File, b"a"),
        Err(DirPushError::Full)
    );
}

#[test]
fn a_name_the_kernel_refuses_is_not_written() {
    let long = vec![b'x'; NAME_MAX + 1];
    let longest = vec![b'x'; NAME_MAX];
    for (name, ok) in [
        (&b""[..], false),
        (&b"a/b"[..], false),
        (&b"a\0b"[..], false),
        (&long[..], false),
        (&longest[..], true),
        (&b".."[..], true),
    ] {
        let mut buf = DirentBuf::new(1 << 16);
        let mut plus = DirentPlusBuf::new(1 << 16);
        let want = if ok {
            Ok(())
        } else {
            Err(DirPushError::InvalidName)
        };
        assert_eq!(buf.push(1, 1, EntryKind::File, name), want);
        assert_eq!(
            plus.push(1, 1, EntryKind::File, name, EntryOut::default()),
            want
        );
        assert_eq!(buf.as_bytes().is_empty(), !ok);
        assert_eq!(plus.as_bytes().is_empty(), !ok);
    }
    assert_eq!(NAME_MAX, 1024);
    assert_eq!(
        DirPushError::InvalidName.to_string(),
        "the directory entry's name is empty, too long, or holds '/' or NUL"
    );
    assert_eq!(
        DirPushError::Full.to_string(),
        "the directory entry does not fit in the reply"
    );
}

#[test]
fn a_readdirplus_record_is_the_entry_then_the_dirent_then_the_padded_name() {
    let entry = EntryOut::new(
        0x42,
        7,
        Duration::from_secs(3600),
        Duration::new(1, 5),
        attr(4096),
    );
    let dot = EntryOut::default(); // nodeid 0: the name only
    let mut buf = DirentPlusBuf::new(4096);
    buf.push(0x42, 1, EntryKind::Directory, b"sub", entry)
        .unwrap();
    buf.push(1, 2, EntryKind::Directory, b"..", dot).unwrap();
    let bytes = buf.as_bytes();
    // 152 + 3 = 155, padded to 160; 152 + 2 = 154, padded to 160.
    assert_eq!(bytes.len(), 320);
    let (first, rest) = DirentPlus::read_prefix(bytes).unwrap();
    assert_eq!(first.entry_out, entry);
    assert_eq!(
        (
            first.entry_out.entry_valid,
            first.entry_out.entry_valid_nsec
        ),
        (3600, 0)
    );
    assert_eq!(
        (first.entry_out.attr_valid, first.entry_out.attr_valid_nsec),
        (1, 5)
    );
    assert_eq!(
        first.dirent,
        Dirent {
            ino: 0x42,
            off: 1,
            namelen: 3,
            typ: 4
        }
    );
    assert_eq!(&rest[..8], b"sub\0\0\0\0\0");
    let (second, rest) = DirentPlus::read_prefix(&rest[8..]).unwrap();
    assert_eq!(second.entry_out.nodeid, 0);
    assert_eq!((second.dirent.ino, second.dirent.off), (1, 2));
    assert_eq!(rest, b"..\0\0\0\0\0\0");

    // A third does not fit 320 + 160 in 479 bytes, and the list is unchanged.
    let mut tight = DirentPlusBuf::new(479);
    tight
        .push(0x42, 1, EntryKind::Directory, b"sub", entry)
        .unwrap();
    tight.push(1, 2, EntryKind::Directory, b"..", dot).unwrap();
    let before = tight.clone();
    assert_eq!(
        tight.push(5, 3, EntryKind::File, b"x", entry),
        Err(DirPushError::Full)
    );
    assert_eq!(tight, before);
}
