//! Proves the bytes of every reply payload the library writes, as they reach the device through a
//! `Replier`: the out header with the payload's length, and each reply struct field for field.
//! Proves that the READDIR and READDIRPLUS lists pad each record to 8 bytes, stop at the
//! request's size, and refuse a name the kernel would refuse.
//!
//! Ports the tests of `src/ll/reply.rs` of fuser 0.18.0 (MIT) byte for byte, with their Linux
//! vectors: empty, error, data, entry, attr, open, write, statfs, create and directory (its
//! lock, bmap, xattr_size and xattr_data tests are dropped: those opcodes are not implemented).
//!
//! Catches:
//! - a reply header whose length leaves out the payload, or an errno not negated;
//! - an entry or attribute reply with a validity's seconds and nanoseconds swapped, or a field
//!   of `fuse_attr` out of place;
//! - a directory record not padded to 8 bytes, with the wrong `DT_*` type, or a record that
//!   overflows the request's size or is half written;
//! - an empty name, one with `/` or NUL, or one longer than the kernel's limit, written to a
//!   list (the kernel fails the whole READDIR on it).

#![allow(
    clippy::unwrap_used,
    clippy::expect_used,
    reason = "an integration test: a failed unwrap or expect is the failure it reports"
)]

mod common;

use std::time::{Duration, UNIX_EPOCH};

use common::FakeDevice;
use tsfuse::abi::{
    Attr, AttrOut, DirPushError, Dirent, DirentBuf, DirentPlus, DirentPlusBuf, EntryKind, EntryOut,
    Kstatfs, NAME_MAX, OpenOut, StatfsOut, Timestamp, WriteOut,
};
use tsfuse::{Completion, Errno, Replier, Tokens};

/// The bytes one reply to request `0xdeadbeef` writes.
fn reply(answer: impl FnOnce(Replier) -> Completion) -> Vec<u8> {
    let tokens = Tokens::new();
    let device = FakeDevice::new();
    let done = answer(tokens.register(0xdead_beef, device.clone()));
    assert!(matches!(done, Completion::Written), "{done:?}");
    let raw = device.raw();
    assert_eq!(raw.len(), 1);
    raw[0].clone()
}

/// The attributes of fuser's reply tests: times `0x1234` s and `0x5678` ns, a regular file of
/// mode 0644.
fn attr(blksize: u32) -> Attr {
    let time = Timestamp::from_system_time(UNIX_EPOCH + Duration::new(0x1234, 0x5678));
    Attr {
        ino: 0x11,
        size: 0x22,
        blocks: 0x33,
        atime: time.wire_secs(),
        mtime: time.wire_secs(),
        ctime: time.wire_secs(),
        atimensec: time.nsecs,
        mtimensec: time.nsecs,
        ctimensec: time.nsecs,
        mode: 0o100_644,
        nlink: 0x55,
        uid: 0x66,
        gid: 0x77,
        rdev: 0x88,
        blksize,
        flags: 0,
    }
}

const TTL: Duration = Duration::new(0x8765, 0x4321);

